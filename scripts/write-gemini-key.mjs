// Writes src/app/constants/gemini-key.generated.ts from GEMINI_API_KEY so the
// key never lives in a committed file. Runs before `npm start` / `npm run
// build` (see package.json). Locally the key comes from a gitignored .env;
// on Netlify set GEMINI_API_KEY in the site's environment variables.
//
// A missing key is not a build error: the assistant still renders and tells
// guests it is unavailable instead.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'src/app/constants/gemini-key.generated.ts');

function readDotEnv() {
  const file = join(root, '.env');
  if (!existsSync(file)) return {};
  const vars = {};
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/i);
    if (match) vars[match[1]] = match[2].replace(/^['"]|['"]$/g, '');
  }
  return vars;
}

const key = (process.env.GEMINI_API_KEY ?? readDotEnv().GEMINI_API_KEY ?? '').trim();

writeFileSync(
  out,
  '// Generated by scripts/write-gemini-key.mjs. Do not edit or commit.\n' +
    `export const GEMINI_API_KEY = ${JSON.stringify(key)};\n`,
);

console.log(
  key
    ? 'Gemini key written to src/app/constants/gemini-key.generated.ts'
    : 'GEMINI_API_KEY not set: AI assistant will show as unavailable.',
);
